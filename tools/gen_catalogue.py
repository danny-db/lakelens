"""Generate docs/CATALOGUE.md from the hunt, measure and Tune definitions in app/.

Run from the repo root after changing any hunt, measure or practice:
    python3 tools/gen_catalogue.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "app"))

import hunts  # noqa: E402
import scan  # noqa: E402
import tune  # noqa: E402

OUT = os.path.join(ROOT, "docs", "CATALOGUE.md")


def clean(text) -> str:
    """House style: no em dashes, single-line cells."""
    t = str(text or "").replace(" — ", " - ").replace("—", " - ").replace("–", "-")
    return re.sub(r"\s+", " ", t).strip()


def tables(sql: str) -> str:
    found = sorted(set(re.findall(r"\bsystem\.[a-z_]+\.[a-z_]+", sql or "")))
    return ", ".join(f"`{t}`" for t in found) or "n/a"


def threshold(spec: dict) -> str:
    if not spec:
        return "Informational (no alert)"
    label = clean(spec["metric_label"])
    if spec["kind"] == "presence":
        return f"{label}: medium whenever a row exists (a configuration state, no magnitude)"
    return (f"{label} versus its own normal ({clean(spec['baseline'])}): high at "
            f"{scan.ANOMALY_HIGH_X:g}x, medium at {scan.ANOMALY_MEDIUM_X:g}x; "
            "an entity with no history is medium")


def measure_title(mid: str) -> str:
    for m in hunts.MEASURES:
        if m["id"] == mid:
            return f"{mid} {clean(m['title'])}"
    return mid or "n/a"


def build() -> str:
    cats = {c["id"]: c for c in hunts.CATEGORIES}
    out = ["# LakeLens catalogue: hunts, Tune practices and measures", "",
           "Back to the [README](../README.md).", "",
           f"LakeLens has **{len(hunts.HUNTS)} hunts** that find waste, **{len(tune.PRACTICES)} Tune practices** "
           f"that help you use Databricks well, and **{len(hunts.MEASURES)} measures** that prove a saving. "
           "Everything reads your own `system.*` tables as the signed-in user.", "",
           "The loop is **Spot → Tune → Prove**: a hunt finds the waste, a practice is the fix, and a measure "
           "shows the before and after.", "",
           "_This file is generated by `tools/gen_catalogue.py` from `app/hunts.py` and `app/tune.py`. "
           "Edit those, then re-run the script._", "",
           "## Contents", "",
           "- [Hunts](#hunts)",
           *[f"  - [{c['label']}](#{re.sub(r'[^a-z0-9 -]', '', c['label'].lower()).replace(' ', '-')})"
             for c in hunts.CATEGORIES],
           "- [Tune practices](#tune-practices)",
           "- [Measures](#measures)", "",
           "## Hunts", "",
           "| ID | Hunt | Category | Alerts on |", "|---|---|---|---|"]
    for h in hunts.HUNTS:
        out.append(f"| {h['id']} | {clean(h['title'])} | {cats[h['category']]['label']} | "
                   f"{threshold(hunts.ALERT_SPECS.get(h['id']))} |")
    out.append("")
    for c in hunts.CATEGORIES:
        out += [f"### {c['label']}", "", clean(c["blurb"]), ""]
        for h in [h for h in hunts.HUNTS if h["category"] == c["id"]]:
            out += [f"#### {h['id']} {clean(h['title'])}", "",
                    f"- **What it finds:** {clean(h['eli5'])}",
                    f"- **How to read it:** {clean(h['what'])}",
                    f"- **What to do:** {clean(h['action'])}",
                    f"- **Alerts:** {threshold(hunts.ALERT_SPECS.get(h['id']))}",
                    f"- **Prove the fix with:** {measure_title(h.get('measure'))}",
                    f"- **Reads:** {tables(h['sql'])}", ""]
    out += ["## Tune practices", "",
            "Practices are grouped by the 4-step maturity model.", ""]
    for step in tune.MATURITY:
        out += [f"### Step {step['step']}: {clean(step['name'])}", "", clean(step["blurb"]), ""]
        for p in [p for p in tune.PRACTICES if p["step"] == step["step"]]:
            out += [f"#### {clean(p['title'])}", "",
                    f"- **Why it matters:** {clean(p['eli5'])}",
                    f"- **Typical impact:** {clean(p['metric'])}",
                    f"- **How:** {clean(p['detail'])}", ""]
    out += ["## Measures", "",
            "| ID | Measure | Use when |", "|---|---|---|"]
    for m in hunts.MEASURES:
        out.append(f"| {m['id']} | {clean(m['title'])} | {clean(m['use_when'])} |")
    out.append("")
    for m in hunts.MEASURES:
        out += [f"### {m['id']} {clean(m['title'])}", "",
                f"- **What it shows:** {clean(m['eli5'])}",
                f"- **How to read it:** {clean(m['what'])}",
                f"- **Use when:** {clean(m['use_when'])}",
                f"- **Reads:** {tables(m['sql'])}", ""]
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(build())
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(hunts.HUNTS)} hunts, "
          f"{len(tune.PRACTICES)} practices, {len(hunts.MEASURES)} measures")
