#!/usr/bin/env python3
"""Write docs/skills/unit-economics/SKILL.md, a Genie One skill, from the Unit economics
board's own SQL in app/boards.py, so the skill and the board can never disagree.

    python3 tools/gen_unit_economics_skill.py           # write the file
    python3 tools/gen_unit_economics_skill.py --check   # exit 1 if the file is out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "app"))
import boards  # noqa: E402

OUT = os.path.join(ROOT, "docs", "skills", "unit-economics", "SKILL.md")

# Anything that would tie the skill to one account, or a long dash, fails the run.
FORBIDDEN = {
    "an id-length number": re.compile(r"\b\d{9,}\b"),
    "a UUID": re.compile(r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b", re.I),
    "a hex id": re.compile(r"\b[0-9a-f]{16}\b"),
    "a workspace URL": re.compile(r"https://[\w.-]+\.(cloud\.databricks\.com|azuredatabricks\.net|gcp\.databricks\.com)"),
    "an em or en dash": re.compile("[\u2013\u2014]"),
}

CHART_GUIDE = {
    "table": "Show the four headline unit costs (kind kpi) as tiles, each with its value, coverage and "
             "definition, then the inputs as a table with the coverage column next to each value. Show "
             "the effective discount only when the account has prices.",
    "lines": "Draw a line chart with one line per unit cost and a logarithmic value axis: the three "
             "costs sit orders of magnitude apart, and on a log axis a doubling is the same height for "
             "each. Call out the latest week when a cost reaches {medium}× its median of the earlier "
             "weeks (high at {high}×), the multiples LakeLens alerts use.",
    "bar": "Draw a bar chart of spend_usd by the first column, sorted by spend, and label each bar "
           "with its percentage.",
}


def render() -> str:
    board = next(b for b in boards.BOARDS if b["id"] == "econ")
    derived = [k for k in boards.ECON_KPIS if k.kind == "kpi" or k.metric == "Effective discount"]
    inputs = [k for k in boards.ECON_KPIS if k not in derived]
    no_storage = {"Query 1": boards._stored_total(False), "Query 2": boards._stored_weekly(False)}
    guide = {c: g.format(medium=f"{boards.ANOMALY_MEDIUM_X:g}", high=f"{boards.ANOMALY_HIGH_X:g}")
             for c, g in CHART_GUIDE.items()}
    out = [
        "---",
        "name: unit-economics",
        "description: Work out this account's Databricks unit economics from system tables only. Cost per "
        "query, per monthly active user (all identities and people), per TiB of data under management and "
        "the effective discount, each with the share of spend it rests on. Use when someone asks what a "
        "query, a user or a terabyte of data costs, or what discount the account gets.",
        "---",
        "",
        "# Unit economics from system tables",
        "",
        "Generated by `tools/gen_unit_economics_skill.py` from the LakeLens Unit economics board "
        "(`app/boards.py`). Edit the board and regenerate; do not edit this file by hand.",
        "",
        "Every query reads only `system.billing`, `system.query`, `system.access` and `system.storage` "
        "tables, so it runs in any account that has system tables enabled. Each figure uses the account's "
        "price from `system.billing.account_prices` where one is set for the SKU, and list price otherwise.",
        "",
        "## Step 1. Anchor the window",
        "",
        "The window holds full days only. Billing writes most of a day's records that day and the rest the "
        "next day, so each query ends its window on the newest usage day whose usage runs to midnight and "
        "whose next-day records have landed, and otherwise the day before (the `latest`, `newest`, `bounds` "
        "and `win` CTEs). It uses those same dates for billing `usage_date`, query history `start_time`, "
        "audit `event_date` and storage `snapshot_date`. Do not use `current_date()` as the end: partial "
        "days make every unit cost look cheaper.",
        "",
        "## Step 2. Run the queries",
        "",
    ]
    for i, p in enumerate(board["panels"], 1):
        out += [f"### Query {i}. {p['title']}", "", p["eli5"], ""]
        if p.get("note"):
            out += [p["note"], ""]
        out += ["```sql", p["sql"].strip(), "```", ""]
        if p.get("without_storage"):
            stub = no_storage[f"Query {i}"].split("AS (", 1)[1].rsplit(")", 1)[0]
            out += [f"If the account can't read `{boards.STORAGE_TABLE}`, replace the `stored` CTE with "
                    f"`{stub}` and leave the data-under-management figures out.", ""]
    out += [
        "## Step 3. Read the derived metrics",
        "",
        "Query 1 returns these rows already computed. `kind` is kpi for the headline unit costs and input "
        "for the raw inputs. `value` uses the account's price where one is set and list price otherwise, "
        "and `coverage` is the share of spend the ratio rests on.",
        "",
        "| Metric | Formula |",
        "|---|---|",
        *[f"| {k.metric} | {k.definition} |" for k in derived],
        "",
        "Raw inputs in the same table:",
        "",
        *[f"- {k.metric}: {k.definition}." for k in inputs],
        "",
        "What the workspace sets mean:",
        "",
        "- Query-workspace spend is the spend of workspaces with at least one finished query in "
        "`system.query.history` in the window.",
        "- Audit-workspace spend is the spend of workspaces with at least one event in "
        "`system.access.audit` in the window.",
        f"- Data under management comes from `{boards.STORAGE_TABLE}`: each table at its newest snapshot in "
        "the window unless it was dropped by the window's end, at its total size (active plus vacuumable "
        "files) where it reports one and its active size otherwise. Cost per TiB is total spend over that "
        "volume. The table lists only the current region's metastore, so on an account with workspaces "
        "in several regions the ratio reads high; say so when you quote it.",
        "",
        "## Step 4. Visualise",
        "",
        *[f"- Query {i}, {p['title']}. {guide[p['chart']]}" for i, p in enumerate(board["panels"], 1)],
        "",
        "## Caveats",
        "",
        "- Billing covers every workspace in the account. Query history and audit list fewer (they are "
        "regional and only hold workspaces with activity), so each ratio divides only the spend of the "
        "workspaces its denominator can see. Always quote a ratio with its coverage.",
        "- User counts use `approx_count_distinct`, so say approx. An identity with an email is a person; "
        "a UUID is a service principal.",
        "- Each figure uses the account price where `system.billing.account_prices` has one for the SKU "
        "and list price otherwise, so no discount is ever invented. With no account prices every figure "
        "is at list price and the effective discount has nothing to show; with prices for only some SKUs "
        "it is marked partial. Account prices in a currency other than the list price's are not compared.",
        f"- `{boards.STORAGE_TABLE}` is new. Where its history starts inside the trend's twelve weeks, the "
        "data-under-management line starts with it.",
        "- Sum `read_bytes` as DOUBLE; the BIGINT sum overflows on large accounts.",
        "",
    ]
    text = "\n".join(out)
    for what, rx in FORBIDDEN.items():
        hit = rx.search(text)
        if hit:
            sys.exit(f"refusing to write {OUT}: it contains {what} ({hit.group(0)!r})")
    return text


def main():
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit(f"{os.path.relpath(OUT, ROOT)} is out of date: run tools/gen_unit_economics_skill.py")
        print(f"{os.path.relpath(OUT, ROOT)} is up to date")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
