#!/usr/bin/env python3
"""Write docs/skills/unit-economics/SKILL.md, a Genie One skill, from the Unit economics
board's own SQL in app/boards.py, so the skill and the board can never disagree.

    python3 tools/gen_unit_economics_skill.py           # write the file
    python3 tools/gen_unit_economics_skill.py --check   # exit 1 if the file is out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "app"))
import boards  # noqa: E402

OUT = os.path.join(ROOT, "docs", "skills", "unit-economics", "SKILL.md")

# Anything that would tie the skill to one account, or a long dash, fails the run.
FORBIDDEN = {
    "an id-length number": re.compile(r"\b\d{9,}\b"),
    "a UUID": re.compile(r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b", re.I),
    "a hex id": re.compile(r"\b[0-9a-f]{16}\b"),
    "a workspace URL": re.compile(r"https://[\w.-]+\.(cloud\.databricks\.com|azuredatabricks\.net|gcp\.databricks\.com)"),
    "an em or en dash": re.compile("[\u2013\u2014]"),
}

CHART_GUIDE = {
    "table": "Show it as a table with every column. Lead with the derived metrics a to e and the "
             "effective discount, and keep the coverage column next to each value.",
    "lines": "Draw a line chart with one line per unit cost and a logarithmic value axis: the three "
             "costs sit orders of magnitude apart, and on a log axis a doubling is the same height for "
             "each. Call out the latest week when a cost reaches {medium}× its median of the earlier "
             "weeks (high at {high}×), the multiples LakeLens alerts use.",
    "bar": "Draw a bar chart of spend_usd by the first column, sorted by spend, and label each bar "
           "with its percentage.",
}


def render() -> str:
    board = next(b for b in boards.BOARDS if b["id"] == "econ")
    derived = sorted((k for k in boards.ECON_KPIS if re.match(r"[a-e]\. ", k.metric) or k.metric == "Effective discount"),
                     key=lambda k: (k.metric == "Effective discount", k.metric))
    inputs = [k for k in boards.ECON_KPIS if k not in derived]
    guide = {c: g.format(medium=f"{boards.ANOMALY_MEDIUM_X:g}", high=f"{boards.ANOMALY_HIGH_X:g}")
             for c, g in CHART_GUIDE.items()}
    out = [
        "---",
        "name: unit-economics",
        "description: Work out this account's Databricks unit economics from system tables only. Cost per "
        "query, per monthly active user, per TiB read, DBSQL cost per TiB read and the effective discount, "
        "each with the share of spend it rests on. Use when someone asks what a query, a user or a terabyte "
        "costs, or what discount the account gets.",
        "---",
        "",
        "# Unit economics from system tables",
        "",
        "Generated by `tools/gen_unit_economics_skill.py` from the LakeLens Unit economics board "
        "(`app/boards.py`). Edit the board and regenerate; do not edit this file by hand.",
        "",
        "Every query reads only `system.billing`, `system.query` and `system.access` tables, so it runs in "
        "any account that has system tables enabled. Dollars are list price unless the account has rows in "
        "`system.billing.account_prices`.",
        "",
        "## Step 1. Anchor the window",
        "",
        "The newest `usage_date` in `system.billing.usage` is still loading. Each query ends its window the "
        "day before it (the `bounds` and `win` CTEs) and uses those same dates for billing `usage_date`, "
        "query history `start_time` and audit `event_date`. Do not use `current_date()` as the end: partial "
        "days make every unit cost look cheaper.",
        "",
        "## Step 2. Run the queries",
        "",
    ]
    for i, p in enumerate(board["panels"], 1):
        out += [f"### Query {i}. {p['title']}", "", p["eli5"], ""]
        if p.get("note"):
            out += [p["note"], ""]
        out += ["```sql", p["sql"].strip(), "```", ""]
    out += [
        "## Step 3. Read the derived metrics",
        "",
        "Query 1 returns these rows already computed. `value` is at list price, `discounted` at the "
        "account's own prices, and `coverage` is the share of spend the ratio rests on.",
        "",
        "| Metric | Formula |",
        "|---|---|",
        *[f"| {k.metric} | {k.definition} |" for k in derived],
        "",
        "Raw inputs in the same table:",
        "",
        *[f"- {k.metric}: {k.definition}." for k in inputs],
        "",
        "What the workspace sets mean:",
        "",
        "- Query-workspace spend is the spend of workspaces with at least one finished query in "
        "`system.query.history` in the window.",
        "- Audit-workspace spend is the spend of workspaces with at least one event in "
        "`system.access.audit` in the window.",
        "- DBSQL-workspace SQL spend is the `SQL` product spend of workspaces with at least one finished "
        "query on a SQL warehouse.",
        "",
        "## Step 4. Visualise",
        "",
        *[f"- Query {i}, {p['title']}. {guide[p['chart']]}" for i, p in enumerate(board["panels"], 1)],
        "",
        "## Caveats",
        "",
        "- Billing covers every workspace in the account. Query history and audit list fewer (they are "
        "regional and only hold workspaces with activity), so each ratio divides only the spend of the "
        "workspaces its denominator can see. Always quote a ratio with its coverage.",
        "- User counts use `approx_count_distinct`, so say approx. An identity with an email is a person; "
        "a UUID is a service principal.",
        "- With no account prices, the discounted figures and the effective discount say unavailable. "
        "With prices for only some SKUs they are marked partial: those rows use the account price and "
        "the rest stay at list, so no discount is ever invented. Account prices in a currency other than "
        "the list price's are not compared.",
        "- Sum `read_bytes` as DOUBLE; the BIGINT sum overflows on large accounts.",
        "",
    ]
    text = "\n".join(out)
    for what, rx in FORBIDDEN.items():
        hit = rx.search(text)
        if hit:
            sys.exit(f"refusing to write {OUT}: it contains {what} ({hit.group(0)!r})")
    return text


def main():
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit(f"{os.path.relpath(OUT, ROOT)} is out of date: run tools/gen_unit_economics_skill.py")
        print(f"{os.path.relpath(OUT, ROOT)} is up to date")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
